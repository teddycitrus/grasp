"""Staged diff parsing, noise filtering, secret redaction and meaningful-line counting."""
from __future__ import annotations

import math
import re
import subprocess
from collections import Counter
from dataclasses import dataclass, field
from fnmatch import fnmatch
from pathlib import Path, PurePosixPath

CONTEXT = 6


@dataclass
class Hunk:
    old_start: int
    new_start: int
    header: str = ""
    lines: list[str] = field(default_factory=list)

    def numbered(self):
        """Yield (prefix, text, old_line, new_line); the missing side is None."""
        o, n = self.old_start, self.new_start
        for line in self.lines:
            p, t = line[:1], line[1:]
            if p == "+":
                yield "+", t, None, n
                n += 1
            elif p == "-":
                yield "-", t, o, None
                o += 1
            else:
                yield " ", t, o, n
                o, n = o + 1, n + 1


@dataclass
class FileDiff:
    path: str
    old_path: str | None = None
    binary: bool = False
    new_file: bool = False
    deleted: bool = False
    hunks: list[Hunk] = field(default_factory=list)

    def changed(self, prefix: str) -> list[str]:
        return [ln[1:] for h in self.hunks for ln in h.lines if ln[:1] == prefix]


# ---------------------------------------------------------------- reading

def git(*args: str, cwd: str | Path | None = None, check: bool = True) -> str:
    r = subprocess.run(["git", *args], cwd=cwd, capture_output=True, check=check)
    return r.stdout.decode("utf-8", errors="replace")


def staged_diff(cwd=None) -> str:
    return git("-c", "core.quotepath=false", "diff", "--cached", "--no-color", "--no-ext-diff",
               "--no-textconv", f"-U{CONTEXT}", "-M", cwd=cwd)


def staged_source(path: str, side: str, cwd=None) -> str | None:
    """File content at HEAD ('old') or in the index ('new')."""
    r = subprocess.run(["git", "show", f"{'HEAD' if side == 'old' else ''}:{path}"], cwd=cwd, capture_output=True)
    return r.stdout.decode("utf-8", errors="replace") if r.returncode == 0 else None


HUNK_RE = re.compile(r"^@@ -(\d+)(?:,\d+)? \+(\d+)(?:,\d+)? @@ ?(.*)$")


def _strip_prefix(p: str) -> str:
    p = p.split("\t")[0].strip('"')
    return p[2:] if p[:2] in ("a/", "b/") else p


def parse_diff(text: str) -> list[FileDiff]:
    files: list[FileDiff] = []
    cur = hunk = None
    for line in text.splitlines():
        if line.startswith("diff --git "):
            m = re.match(r'diff --git "?a/(.*?)"? "?b/(.*?)"?$', line)
            cur = FileDiff(path=m.group(2), old_path=m.group(1)) if m else FileDiff(path=line.split()[-1])
            files.append(cur)
            hunk = None
        elif cur is None:
            continue
        elif hunk is not None and line[:1] in ("", " ", "+", "-"):
            hunk.lines.append(line if line else " ")
        elif line.startswith("\\"):
            continue
        elif m := HUNK_RE.match(line):
            hunk = Hunk(int(m.group(1)), int(m.group(2)), m.group(3))
            cur.hunks.append(hunk)
        elif line.startswith("new file mode"):
            cur.new_file = True
        elif line.startswith("deleted file mode"):
            cur.deleted = True
        elif line.startswith(("Binary files", "GIT binary patch")):
            cur.binary = True
        elif line.startswith("+++ ") and "/dev/null" not in line:
            cur.path = _strip_prefix(line[4:])
        elif line.startswith("--- ") and "/dev/null" not in line:
            cur.old_path = _strip_prefix(line[4:])
    return files


# ---------------------------------------------------------------- filtering

LOCKFILES = {
    "package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb", "bun.lock",
    "poetry.lock", "Pipfile.lock", "uv.lock", "pdm.lock", "Cargo.lock", "Gemfile.lock", "composer.lock",
    "go.sum", "mix.lock", "pubspec.lock", "Podfile.lock", "packages.lock.json", "flake.lock",
}
GENERATED = ["*.min.js", "*.min.css", "*.map", "*_pb2.py", "*_pb2_grpc.py", "*.pb.go", "*.generated.*",
             "*.g.dart", "*.snap", "*.lock"]
VENDORED = {"vendor", "node_modules", "third_party", "third-party", ".venv", "venv", "site-packages", "dist",
            "__pycache__", "bower_components"}
SECRET_FILES = [".env", ".env.*", "*.env", "*.pem", "*.key", "*.p12", "*.pfx", "*.keystore", "*.jks", "id_rsa*",
                "id_dsa*", "id_ecdsa*", "id_ed25519*", ".netrc", ".npmrc", ".pypirc", "credentials",
                "credentials.json", "*.credentials", "secrets.*", "secret.*", ".htpasswd", "*.tfvars"]
GENERATED_MARKERS = re.compile(r"@generated|do not edit|auto-generated|autogenerated", re.I)


def load_ignore(root) -> list[str]:
    p = Path(root) / ".graspignore"
    if not p.exists():
        return []
    lines = (ln.strip() for ln in p.read_text(encoding="utf-8", errors="replace").splitlines())
    return [ln for ln in lines if ln and not ln.startswith("#")]


def _matches(path: str, patterns) -> bool:
    p = PurePosixPath(path)
    for pat in patterns:
        if pat.endswith("/"):
            if pat.strip("/") in p.parts[:-1] or path.startswith(pat.lstrip("/")):
                return True
        elif fnmatch(path, pat.lstrip("/")) or fnmatch(p.name, pat):
            return True
    return False


def noise_reason(f: FileDiff, ignore=()) -> str | None:
    name = PurePosixPath(f.path).name
    added = f.changed("+")
    if f.binary:
        return "binary"
    if name in LOCKFILES:
        return "lockfile"
    if _matches(f.path, SECRET_FILES):
        return "secret-looking file"
    if set(PurePosixPath(f.path).parts[:-1]) & VENDORED:
        return "vendored"
    if _matches(f.path, GENERATED) or any(GENERATED_MARKERS.search(ln) for ln in added[:5]):
        return "generated"
    if added and (max(map(len, added)) > 1000 or sum(map(len, added)) / len(added) > 300):
        return "minified"
    if _matches(f.path, ignore):
        return ".graspignore"
    return None


# ---------------------------------------------------------------- redaction

REDACTED = "[REDACTED]"
SECRET_RES = [re.compile(p) for p in (
    r"\b(?:AKIA|ASIA)[0-9A-Z]{16}\b",
    r"\bsk-[A-Za-z0-9_\-]{20,}",
    r"\bgh[pousr]_[A-Za-z0-9]{30,}",
    r"\bgithub_pat_[A-Za-z0-9_]{30,}",
    r"\bxox[abposr]-[A-Za-z0-9-]{10,}",
    r"\bAIza[0-9A-Za-z_\-]{35}",
    r"\beyJ[A-Za-z0-9_-]{8,}\.eyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}",
    r"(?i)(?<=bearer )[A-Za-z0-9._\-]{16,}",
    r"(?<=://)[^\s:/@]+:[^\s@/]+(?=@)",
)]
ASSIGN_RE = re.compile(
    r"(?i)([\w.-]*(?:api[_-]?key|secret|token|passw(?:or)?d|pwd|credential|private[_-]?key)[\w.-]*"
    r"[\"']?\s*[:=]\s*)([\"'])([^\"'\s]{6,})\2")
ENV_RE = re.compile(r"(?i)\b(\w*(?:KEY|SECRET|TOKEN|PASSWORD)\w*=)([^\s\"']{8,})")
PROSE_RE = re.compile(r"(?i)\b((?:passw(?:or)?d|pwd|secret|token|api[_ -]?key)(?:\s*[:=]\s*|\s+(?:is\s+)?))"
                      r"(?=[^\s\"',;()]*\d)([^\s\"',;().]{6,})")
QUOTED_RE = re.compile(r"([\"'])([A-Za-z0-9+/=_\-]{24,})\1")
PEM_START, PEM_END = re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"), re.compile(r"-----END [A-Z ]*PRIVATE KEY")


def _entropy(s: str) -> float:
    return -sum(c / len(s) * math.log2(c / len(s)) for c in Counter(s).values())


def redact(text: str) -> str:
    for rx in SECRET_RES:
        text = rx.sub(REDACTED, text)
    text = ASSIGN_RE.sub(lambda m: f"{m.group(1)}{m.group(2)}{REDACTED}{m.group(2)}", text)
    text = ENV_RE.sub(lambda m: m.group(1) + REDACTED, text)
    text = PROSE_RE.sub(lambda m: m.group(1) + REDACTED, text)

    def high_entropy(m):
        s = m.group(2)
        risky = re.search(r"\d", s) and re.search(r"[A-Za-z]", s) and _entropy(s) > 3.5
        return f"{m.group(1)}{REDACTED}{m.group(1)}" if risky else m.group(0)
    return QUOTED_RE.sub(high_entropy, text)


def _redact_hunk(h: Hunk) -> Hunk:
    out, in_pem = [], False
    for ln in h.lines:
        if PEM_START.search(ln):
            in_pem = True
        out.append(ln[:1] + (REDACTED if in_pem else redact(ln[1:])))
        if PEM_END.search(ln):
            in_pem = False
    return Hunk(h.old_start, h.new_start, redact(h.header), out)


def prepare(text: str, ignore=()) -> tuple[list[FileDiff], dict[str, str]]:
    """Parse, drop noise files, redact the rest. Returns (kept files, {skipped path: reason})."""
    kept, skipped = [], {}
    for f in parse_diff(text):
        reason = noise_reason(f, ignore)
        if reason:
            skipped[f.path] = reason
            continue
        f.hunks = [_redact_hunk(h) for h in f.hunks]
        kept.append(f)
    return kept, skipped


# ---------------------------------------------------------------- counting

C_LIKE = {".c", ".h", ".cc", ".cpp", ".hpp", ".cs", ".m", ".mm", ".swift", ".java", ".kt", ".go", ".rs", ".js",
          ".jsx", ".ts", ".tsx", ".php", ".scala", ".dart"}
COMMENT_RE = re.compile(r"^(//|/\*|\*/|\*(\s|$)|--(\s|$)|<!--|-->|\"\"\"|''')")
IMPORT_RE = re.compile(
    r"^(import\s|import\(|from\s+[\w.]+\s+import\b|#\s*include\s|#import\s|using\s+[\w.=\s]+;|use\s+[\w:{}, *]+;"
    r"|require(_once)?[\s(]|(const|let|var)\s+[\w{}, ]+\s*=\s*require\(|export\s+.*\bfrom\s|package\s+[\w.]+;?$"
    r"|extern crate\s|@import\s)")


def _code_lines(lines: list[str], ext: str) -> list[str]:
    """Whitespace-normalised lines that are not blank, comment-only or import-only."""
    out, in_import = [], False
    for raw in lines:
        s = raw.strip()
        if in_import:
            in_import = not re.search(r"[)}]", s)
            continue
        if not s or COMMENT_RE.match(s) or (s.startswith("#") and ext not in C_LIKE):
            continue
        if IMPORT_RE.match(s):
            in_import = s.endswith(("(", "{"))
            continue
        out.append(re.sub(r"\s+", "", s))
    return out


def meaningful_lines(files: list[FileDiff]) -> int:
    total = 0
    for f in files:
        ext = PurePosixPath(f.path).suffix.lower()
        removed = Counter(_code_lines(f.changed("-"), ext))
        added = Counter(_code_lines(f.changed("+"), ext))
        moved = removed & added  # whitespace-only or moved lines cancel out
        total += sum((removed - moved).values()) + sum((added - moved).values())
    return total


def question_count(lines: int, threshold: int) -> int:
    return 0 if lines < threshold else 2 if lines <= 60 else 3


# ---------------------------------------------------------------- helpers for question generation

IDENT_RE = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*")


def identifiers(files: list[FileDiff]) -> set[str]:
    out = set()
    for f in files:
        out |= set(IDENT_RE.findall(f.path))
        for h in f.hunks:
            for ln in h.lines:
                out |= set(IDENT_RE.findall(ln[1:]))
    return {t for t in out if len(t) >= 2}


def snippet(f: FileDiff, line: int | None = None, side: str = "new", needle: str | None = None,
            max_lines: int = 25) -> str:
    """Up to max_lines of the hunk around a line number or the first changed line containing needle."""
    col = 3 if side == "new" else 2
    tests = [lambda r: line is not None and r[col] == line,
             lambda r: bool(needle) and needle in r[1] and r[0] != " ",
             lambda r: bool(needle) and needle in r[1],
             lambda r: r[0] != " "]
    hunks = [list(h.numbered()) for h in f.hunks]
    found = next(((rows, i) for test in tests for rows in hunks for i, r in enumerate(rows) if test(r)), None)
    if found is None:
        return ""
    rows, i = found
    start = max(0, min(i - 8, len(rows) - max_lines))
    out = []
    for p, t, o, n in rows[start:start + max_lines]:
        num = n if n is not None else o
        out.append(f"{num:>5} {p} {t.rstrip()}")
    return "\n".join(out)


def render(files: list[FileDiff], max_tokens: int) -> str:
    """Compact unified diff text for a model, largest-change files first, cut at ~4 chars per token."""
    budget, parts = max_tokens * 4, []
    for f in sorted(files, key=lambda f: -meaningful_lines([f])):
        body = "\n".join([f"--- {f.path}"] + [
            f"@@ -{h.old_start} +{h.new_start} @@ {h.header}".rstrip() + "\n" + "\n".join(h.lines) for h in f.hunks])
        if len(body) > budget:
            parts.append(body[:budget] + "\n[diff truncated]")
            break
        parts.append(body)
        budget -= len(body)
    return "\n".join(parts)
