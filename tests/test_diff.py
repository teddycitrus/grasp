import pytest
from conftest import FIXTURES, make_diff

from grasp.diff import (REDACTED, load_ignore, meaningful_lines, parse_diff, prepare, question_count, redact, render,
                        snippet)


def load(name):
    return (FIXTURES / name).read_text(encoding="utf-8")


def test_lockfile_is_dropped():
    files, skipped = prepare(load("lockfile.diff"))
    assert skipped == {"package-lock.json": "lockfile"}
    assert [f.path for f in files] == ["src/app.js"]


def test_binary_is_dropped():
    files, skipped = prepare(load("binary.diff"))
    assert skipped == {"assets/logo.png": "binary"}
    assert [f.path for f in files] == ["src/util.py"]


def test_env_files_are_dropped_and_their_values_never_kept():
    files, skipped = prepare(load("env_file.diff"))
    assert skipped == {".env": "secret-looking file", "config/prod.env": "secret-looking file"}
    text = render(files, 10_000)
    for value in ("envfilepass99", "rk_live_envfilesecretvalue123", "prodenvsecretvalue456"):
        assert value not in text


@pytest.mark.parametrize("path,reason", [
    ("vendor/lib/x.go", "vendored"), ("node_modules/a/index.js", "vendored"), ("static/app.min.js", "minified"),
    ("api/user_pb2.py", "generated"), ("yarn.lock", "lockfile"), ("certs/server.pem", "secret-looking file"),
    ("home/.ssh/id_rsa", "secret-looking file"),
])
def test_noise_paths(path, reason):
    diff = make_diff(path, "a = 1\n", "a = 2\nb = 3\n")
    files, skipped = prepare(diff)
    expected = "generated" if reason == "minified" else reason
    assert files == [] and skipped[path] == expected


def test_generated_marker_and_minified_content():
    gen = make_diff("src/schema.py", "", "# Code generated by protoc. DO NOT EDIT.\nx = 1\n")
    mini = make_diff("src/bundle.js", "", "var a=" + "1+" * 800 + "1;\n")
    assert prepare(gen)[1] == {"src/schema.py": "generated"}
    assert prepare(mini)[1] == {"src/bundle.js": "minified"}


def test_graspignore(tmp_path):
    (tmp_path / ".graspignore").write_text("# comment\ndocs/\n*.sql\nscripts/gen_*.py\n")
    ignore = load_ignore(tmp_path)
    diff = "".join(make_diff(p, "x = 1\n", "x = 2\n") for p in
                   ["docs/guide.py", "db/schema.sql", "scripts/gen_api.py", "scripts/run.py"])
    files, skipped = prepare(diff, ignore)
    assert [f.path for f in files] == ["scripts/run.py"]
    assert set(skipped.values()) == {".graspignore"}


FAKE_SECRETS = ["AKIAIOSFODNN7EXAMPLE", "sk-test0FAKE0KEY0abcdefghijklmnop", "hunter2hunter2", "dsnpassw0rd",
                "eyJhbGciOiJIUzI1NiJ9.eyJzdWIiOiIxMjM0NTY3ODkwIn0", "q8Zr2Lx9Vb4Nm7Kp3Wd6Ty1Hg5Jc0Fs",
                "abcdefghijklmnop1234567890"]


def test_fake_keys_are_redacted_but_code_survives():
    files, _ = prepare(load("fake_keys.diff"))
    text = render(files, 10_000) + "".join(snippet(f) for f in files)
    for secret in FAKE_SECRETS:
        assert secret not in text, secret
    assert text.count(REDACTED) >= len(FAKE_SECRETS)
    assert "if retries < 0:" in text and "self.base_url" in text


