def test_parse_new_deleted_renamed():
    text = (
        "diff --git a/new.py b/new.py\nnew file mode 100644\n--- /dev/null\n+++ b/new.py\n@@ -0,0 +1 @@\n+x = 1\n"
        "diff --git a/old.py b/old.py\ndeleted file mode 100644\n--- a/old.py\n+++ /dev/null\n@@ -1 +0,0 @@\n-y = 2\n"
        "diff --git a/a.py b/b.py\nsimilarity index 90%\nrename from a.py\nrename to b.py\n--- a/a.py\n+++ b/b.py\n"
        "@@ -1 +1 @@ def f():\n-z = 1\n+z = 2\n")
    new, old, ren = parse_diff(text)
    assert new.new_file and new.path == "new.py" and new.changed("+") == ["x = 1"]
    assert old.deleted and old.path == "old.py" and old.changed("-") == ["y = 2"]
    assert (ren.old_path, ren.path, ren.hunks[0].header) == ("a.py", "b.py", "def f():")


def test_removed_line_starting_with_dashes_is_not_a_header():
    text = make_diff("q.sql", "-- note\nselect 1;\n", "select 2;\n")
    (f,) = parse_diff(text)
    assert "-- note" in f.changed("-")


def test_snippet_is_bounded_and_centered():
    before = "".join(f"x{i} = {i}\n" for i in range(100))
    after = before.replace("x50 = 50", "x50 = 5000")
    (f,) = parse_diff(make_diff("big.py", before, after))
    s = snippet(f, needle="5000")
    assert 10 <= len(s.splitlines()) <= 25 and "x50 = 5000" in s


def test_render_respects_budget():
    after = "".join(f"value_{i} = compute({i})\n" for i in range(2000))
    files, _ = prepare(make_diff("big.py", "", after))
    out = render(files, 500)
    assert len(out) <= 500 * 4 + 50 and out.endswith("[diff truncated]")
